  id           uuid primary key default gen_random_uuid(),
  job_role     text not null,
  doc_type     text not null,
  title        text not null,
  body_text    text not null,
  -- 문안을 고치면 올립니다. 스냅샷은 이미 복사된 뒤이므로 과거 데모 세션은 영향받지 않습니다.
  seed_version text not null,
  created_at   timestamptz not null default now(),

  constraint demo_documents_job_role_check check (
    job_role in ('pm', 'pd', 'security', 'ai', 'engineer')
  ),
  constraint demo_documents_doc_type_check check (
    doc_type in ('resume', 'job_description')
  ),
  constraint demo_documents_title_len check (char_length(title) between 1 and 120),
  -- interview_sessions.*_text_snapshot의 CHECK(1~200000)와 같은 범위입니다.
  -- 스냅샷으로 복사되므로 여기서 넘치면 복사 시점에 터집니다.
  constraint demo_documents_body_len check (char_length(body_text) between 1 and 200000),
  constraint demo_documents_seed_version_len check (char_length(seed_version) between 1 and 20),

  -- 직군당 이력서 1 + JD 1. 이 제약이 곧 "총 10행"의 보증입니다.
  constraint demo_documents_role_type_unique unique (job_role, doc_type)
);

