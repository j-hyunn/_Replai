-- D35-3 — `demo_documents`: 데모용 시드 이력서·JD (사용자 데이터가 아닌 픽스처)
--
--   원본 명세: `_workspace/00_input/decisions.md` D35-3,
--              `_workspace/01_domain_model.md` 3.1-a절.
--
--   **`user_id`가 없습니다.** 이것은 우리가 작성한 픽스처이지 사용자 데이터가 아닙니다.
--   그래서 `documents` 테이블에 넣지 않았습니다 — 넣었다면 `documents`의 모든 RLS 정책에
--   "단, 이 UUID는 예외" 분기가 생기고, 소유자로 쓸 사람 아닌 계정을 `auth.users`에
--   만들어야 했을 것입니다.
--
--   **RLS를 통과시킬 일이 없습니다.** 데모 세션 생성 시 서버가 `body_text`를 읽어
--   `interview_sessions.resume_text_snapshot` / `jd_text_snapshot`에 **복사해 넣습니다.**
--   `resume_document_id` / `jd_document_id`는 NULL로 둡니다(둘 다 nullable).
--   이것은 예외 처리가 아니라 **D6(문서는 스냅샷) 설계를 그대로 쓰는 것**이며, 그 덕에
--   면접관·플래너·평가자는 자기가 데모를 돌고 있다는 사실을 알 필요가 없습니다.
--
--   시드 문안의 인물·회사·수치는 **전부 가공**입니다. 실재 인물의 이력서를 넣지 않습니다.

